package eu.wohlben.qits.cli.access.contracts;

import eu.wohlben.qits.cli.access.TestCli;
import eu.wohlben.qits.cli.access.daemon.Sleeper;
import eu.wohlben.qits.cli.access.platform.CliContext;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Clock;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * {@code qits contracts coverage} (qits-1940) over a document shaped as qits-workspace-daemon's (two
 * servers, one of them a template) and an index shaped as the recorder writes it: its stdout, its
 * {@code --out} TSV and its exit codes.
 */
class CoverageCommandTest {

    /** The header and the {@code ---} the export test writes, as in qits-projects-service's. */
    static final String DOCUMENT = """
            # THIS FILE IS GENERATED BY OpenApiSchemaExportTest — DO NOT EDIT MANUALLY.
            ---
            openapi: 3.1.0
            servers:
              - url: /
                description: The daemon addressed directly.
              - url: /workspaces/container/{workspaceId}
            paths:
              /commands:
                summary: Not an operation.
                parameters: []
                get:
                  operationId: listCommands
                post:
                  operationId: runCommand
              /commands/{commandId}:
                get:
                  operationId: getCommand
                delete:
                  responses: {}
              /health:
                get: {}
            """;

    static final String INDEX = """
            {"formatVersion": 1, "provider": "qits-workspace-daemon", "states": [
              {"name": "a daemon", "operations": [
                {"operationId": "listCommands", "method": "GET", "path": "/commands"},
                {"method": "GET", "path": "/workspaces/container/abc/commands/xyz?verbose=true"}
              ]},
              {"name": "a daemon with no commands", "operations": []}
            ]}
            """;

    @TempDir
    Path dir;

    private Path openapi;
    private Path index;
    private Path tsv;

    record Result(int exit, String out, String err) {
    }

    @BeforeEach
    void files() throws IOException {
        openapi = Files.writeString(dir.resolve("openapi.yml"), DOCUMENT);
        index = Files.writeString(dir.resolve("index.json"), INDEX);
        tsv = dir.resolve(".qits-ci/uncovered-operations.tsv");
    }

    @Test
    void theUncoveredAreNamedInDocumentOrderAndExitThree() throws IOException {
        Result result = coverage("--out", tsv.toString());

        assertThat(result.exit()).as(result.err()).isEqualTo(3);
        assertThat(result.out()).isEqualTo("""
                uncovered: runCommand (POST /commands)
                uncovered: DELETE /commands/{commandId}
                uncovered: GET /health
                golden-master coverage: 2/5 operations covered
                """);
        assertThat(result.err()).isEmpty();
        assertThat(Files.readString(tsv)).isEqualTo("""
                runCommand\tPOST\t/commands
                DELETE /commands/{commandId}\tDELETE\t/commands/{commandId}
                GET /health\tGET\t/health
                """);
    }

    @Test
    void everyOperationCoveredIsExitZeroAndAnEmptyFile() throws IOException {
        Files.writeString(openapi, """
                openapi: 3.0.3
                paths:
                  /commands:
                    get:
                      operationId: listCommands
                """);
        Files.createDirectories(tsv.getParent());
        Files.writeString(tsv, "stale\tGET\t/stale\n");

        Result result = coverage("--out", tsv.toString());

        assertThat(result.exit()).as(result.err()).isZero();
        assertThat(result.out()).isEqualTo("golden-master coverage: all 1 operations covered\n");
        assertThat(tsv).isRegularFile().isEmptyFile();
    }

    @Test
    void aDocumentWithNoOperationsIsCovered() throws IOException {
        Files.writeString(openapi, "openapi: 3.1.0\ninfo:\n  title: nothing\n");

        Result result = coverage("--out", tsv.toString());

        assertThat(result.exit()).as(result.err()).isZero();
        assertThat(result.out()).isEqualTo("golden-master coverage: all 0 operations covered\n");
        assertThat(tsv).isEmptyFile();
    }

    @Test
    void aJsonDocumentIsReadByItsName() throws IOException {
        Path json = Files.writeString(dir.resolve("openapi.json"), """
                {"openapi": "3.1.0", "paths": {"/commands": {"get": {"operationId": "listCommands"},
                  "put": {}}}}
                """);

        Result result = run("contracts", "coverage", "--openapi", json.toString(), "--index", index.toString());

        assertThat(result.exit()).as(result.err()).isEqualTo(3);
        assertThat(result.out()).isEqualTo("uncovered: PUT /commands\ngolden-master coverage: 1/2 operations covered\n");
    }

    @Test
    void withNoGoldenMastersEveryOperationIsUncoveredAndNoIndexIsRead() throws IOException {
        Files.delete(index);

        Result result = coverage("--no-golden-masters", "--out", tsv.toString());

        assertThat(result.exit()).as(result.err()).isEqualTo(3);
        assertThat(result.out()).endsWith("golden-master coverage: 0/5 operations covered (no golden masters declared)\n");
        assertThat(Files.readAllLines(tsv)).hasSize(5).first().isEqualTo("listCommands\tGET\t/commands");
    }

    // --- inputs that cannot be read ----------------------------------------------------------------

    @Test
    void aMissingDocumentIsExitOneAndWritesNoFile() throws IOException {
        Files.createDirectories(tsv.getParent());
        Files.writeString(tsv, "left\tGET\t/over\n");
        Path missing = dir.resolve("docs/openapi.yml");

        Result result = run("contracts", "coverage", "--openapi", missing.toString(), "--index", index.toString(),
                "--out", tsv.toString());

        assertThat(result.exit()).isEqualTo(1);
        assertThat(result.err()).isEqualTo("no exported OpenAPI at " + missing + "\n");
        assertThat(result.out()).isEmpty();
        assertThat(tsv).doesNotExist();
    }

    @Test
    void theDefaultsAreUnderTheWorkingDirectory() {
        // the module's directory has neither file
        Result result = run("contracts", "coverage");

        assertThat(result.exit()).isEqualTo(1);
        assertThat(result.err()).isEqualTo("no exported OpenAPI at docs/openapi.yml\n");
    }

    @Test
    void aMissingIndexIsExitOne() throws IOException {
        Files.delete(index);

        Result result = coverage("--out", tsv.toString());

        assertThat(result.exit()).isEqualTo(1);
        assertThat(result.err()).isEqualTo("no golden-master index at " + index + "\n");
        assertThat(tsv).doesNotExist();
    }

    @Test
    void aMalformedDocumentOrIndexIsExitOne() throws IOException {
        Files.writeString(openapi, "openapi: [unclosed\n");
        Result yaml = coverage();
        assertThat(yaml.exit()).isEqualTo(1);
        assertThat(yaml.err()).startsWith("Could not read the OpenAPI document " + openapi + ": ");

        Files.writeString(openapi, "swagger: \"2.0\"\npaths: {}\n");
        Result swagger = coverage();
        assertThat(swagger.exit()).isEqualTo(1);
        assertThat(swagger.err()).contains("not an OpenAPI 3 document: openapi is missing");

        Files.writeString(openapi, DOCUMENT);
        Files.writeString(index, "{\"formatVersion\": 2, \"provider\": \"p\", \"states\": []}");
        Result version = coverage();
        assertThat(version.exit()).isEqualTo(1);
        assertThat(version.err()).isEqualTo("Could not read the golden-master index " + index
                + ": golden-master index formatVersion 2, only 1 is read\n");
    }

    @Test
    void theGroupAsksForItsCommand() {
        Result help = run("contracts", "coverage", "--help");

        assertThat(help.exit()).isZero();
        assertThat(run("contracts").exit()).isEqualTo(2);
    }

    private Result coverage(String... args) {
        List<String> all = new ArrayList<>(List.of("contracts", "coverage", "--openapi", openapi.toString(),
                "--index", index.toString()));
        all.addAll(List.of(args));
        return run(all.toArray(String[]::new));
    }

    private Result run(String... args) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        CliContext context = new CliContext(Map.of(), InputStream.nullInputStream(),
                new PrintStream(out, true, StandardCharsets.UTF_8), new PrintStream(err, true, StandardCharsets.UTF_8),
                Clock.systemUTC(), Sleeper.real(), name -> null, stop -> { });
        int exit = TestCli.execute(context, args);
        return new Result(exit, out.toString(StandardCharsets.UTF_8), err.toString(StandardCharsets.UTF_8));
    }
}
